import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {MOTOR_MODEL,MOTOR_SHA256} from '../dist/data/malecns-motor.mjs';
import {CONNECTOME,CONNECTOME_SHA256} from '../dist/data/malecns-escape.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const cache=path.join(root,'.cache','malecns-upstream');
const source=JSON.parse(await readFile(path.join(root,'data','SOURCE_DATA.json'),'utf8')).source_files.find(s=>s.name.startsWith('body-neurotransmitters'));
const hash=b=>createHash('sha256').update(b).digest('hex');
const filename=path.join(cache,source.name);
await mkdir(cache,{recursive:true});
let bytes;
try{bytes=await readFile(filename);}catch(error){
  if(error.code!=='ENOENT'||!process.argv.includes('--download'))throw error;
  const response=await fetch(source.url+'?generation='+source.gcs_generation,{signal:AbortSignal.timeout(60000)});
  if(!response.ok)throw Error('Neurotransmitter download failed: HTTP '+response.status);
  bytes=Buffer.from(await response.arrayBuffer());
  if(bytes.length!==source.bytes||hash(bytes)!==source.sha256)throw Error('Source identity mismatch');
  await writeFile(filename,bytes);
}
if(bytes.length!==source.bytes||hash(bytes)!==source.sha256)throw Error('Source identity mismatch');
const ids=[...new Set([...MOTOR_MODEL.neurons,...CONNECTOME.neurons].map(n=>n.bodyId))].sort((a,b)=>a-b);
const identities=path.join(cache,'nt-selected-body-ids.json');
await writeFile(identities,JSON.stringify(ids));
const pythonArg=process.argv.indexOf('--python');
const python=pythonArg>=0?process.argv[pythonArg+1]:process.env.MALECNS_PYTHON||'python';
const extracted=JSON.parse(execFileSync(python,[path.join(root,'scripts','read-neurotransmitters.py'),filename,identities],{encoding:'utf8',maxBuffer:20_000_000}));
if(extracted.records.length!==ids.length||extracted.records.some((r,i)=>r[0]!==ids[i]))throw Error('Body identity mismatch');
const data={schema:1,dataset:'male-cns:v1.0',license:'CC-BY-4.0',source:{url:source.url,bytes:source.bytes,sha256:source.sha256,gcsGeneration:source.gcs_generation,rows:extracted.sourceRows},
 selection:{motorModel:MOTOR_SHA256,reflexModel:CONNECTOME_SHA256,neurons:ids.length},
 annotation:'Exact consensus_nt and supporting prediction fields joined by body ID. Confidence columns belong to their own predictions, not necessarily to consensus_nt. No receptor or synaptic-effect measurements are inferred.',
 columns:extracted.columns,records:extracted.records};
const json=JSON.stringify(data),sha256=hash(json),counts={};
for(const r of data.records)counts[r[1]??'unknown']=(counts[r[1]??'unknown']??0)+1;
const groundTruth=data.records.filter(r=>r[5]!==null&&r[5]!=='').length;
await writeFile(path.join(root,'dist','data','malecns-neurotransmitters.mjs'),'// Generated by scripts/import-neurotransmitters.mjs. Data CC BY 4.0.\nexport const NEUROTRANSMITTER_DATA = '+json+';\nexport const NEUROTRANSMITTER_SHA256 = '+JSON.stringify(sha256)+';\n');
await writeFile(path.join(root,'data','neurotransmitter-manifest.json'),JSON.stringify({schema:1,sha256,source:data.source,selection:data.selection,columns:data.columns,counts,groundTruth,build:{pyarrow:extracted.pyarrow},annotation:data.annotation},null,2)+'\n');
console.log(JSON.stringify({sha256,neurons:ids.length,counts,groundTruth}));
